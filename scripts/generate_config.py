#!/usr/bin/env python3
"""Read .env and write assets/js/config.js for the presentation."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENV_PATH = ROOT / ".env"
OUT_JS_PATH = ROOT / "assets" / "js" / "config.js"
OUT_JSON_PATH = ROOT / "assets" / "config.json"

DEFAULTS = {
    "QR_URL": (
        "https://www.scouts.org.uk/volunteers/running-your-section/"
        "programme-guidance/information-for-volunteers/general-activity-guidance-a-z/"
        "paddlesports/kayaking/"
    ),
    "SLIDE_INTERVAL_MS": 10000,
    "QR_MODAL_TITLE": "Scan for more information",
    "QR_SLIDE_CAPTION": "Scan for Scouts paddlesport and traditional rafting guidance.",
}


def parse_env(text: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        out[key] = value
    return out


def build_config(env: dict[str, str]) -> dict:
    config = dict(DEFAULTS)
    if "QR_URL" in env:
        config["QR_URL"] = env["QR_URL"]
    if "SLIDE_INTERVAL_MS" in env:
        config["SLIDE_INTERVAL_MS"] = int(env["SLIDE_INTERVAL_MS"])
    if "QR_MODAL_TITLE" in env:
        config["QR_MODAL_TITLE"] = env["QR_MODAL_TITLE"]
    if "QR_SLIDE_CAPTION" in env:
        config["QR_SLIDE_CAPTION"] = env["QR_SLIDE_CAPTION"]
    return config


def main() -> None:
    env: dict[str, str] = {}
    if ENV_PATH.is_file():
        env = parse_env(ENV_PATH.read_text(encoding="utf-8"))
    else:
        example = ROOT / ".env.example"
        if example.is_file():
            env = parse_env(example.read_text(encoding="utf-8"))

    config = build_config(env)
    OUT_JS_PATH.parent.mkdir(parents=True, exist_ok=True)
    js_body = (
        "/* Generated by scripts/generate_config.py — edit .env and re-run the script. */\n"
        "window.PRESENTATION_CONFIG = "
        + json.dumps(config, indent=2)
        + ";\n"
    )
    OUT_JS_PATH.write_text(js_body, encoding="utf-8")
    OUT_JSON_PATH.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_JS_PATH.relative_to(ROOT)}")
    print(f"Wrote {OUT_JSON_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
